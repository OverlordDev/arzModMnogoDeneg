RAR_RULES: list[tuple[str, str]] = [
    ("Легендарный", r"легендарн"),
    ("Мифический", r"мифическ"),
    ("Эпический", r"эпическ"),
    ("Уникальный", r"уникальн"),
    ("Редкий", r"редк"),
    ("Хлам", r"хлам"),
    ("Обычный", r"\(обычн|обычн\.|обычный"),
]


def classify(name: str) -> tuple[str, str]:
    low = name.lower()
    cat = "Прочее"
    for c, pat in CAT_RULES:
        if re.search(pat, low):
            cat = c
            break
    rar = ""
    for r, pat in RAR_RULES:
        if re.search(pat, low):
            rar = r
            break
    return cat, rar


def main() -> int:
    items = json.loads(SRC.read_text(encoding="utf-8"))
    n_cat = n_rar = 0
    for it in items:
        cat, rar = classify(it.get("name", ""))
        if cat != "Прочее":
            it["cat"] = cat
            n_cat += 1
        elif not it.get("cat"):
            it["cat"] = cat
        if rar and not it.get("rarity"):
            it["rarity"] = rar
            n_rar += 1
    from collections import Counter
    print("категории:", Counter(i["cat"] for i in items).most_common(20))
    print("редкость:", Counter(i["rarity"] for i in items).most_common(10))
    SRC.write_text(json.dumps(items, ensure_ascii=False), encoding="utf-8")
    print(f"итого {len(items)}, с категорией(не Прочее): {n_cat}, редкость проставлена: {n_rar}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
